TEST_F(AurHardening, OfficialPreviewIncludesTransitivePackagesAndRawResolutionFingerprint) {
    snapshot.official_deps = {"extra/compiler"};
    snapshot.plan.installs = {{{"community"}, {}, "app"}, {{"official"}, "extra", "compiler"}};
    runner.result.out = "extra/compiler 1-1\ncore/runtime 2-1\n";
    ASSERT_TRUE(plan_aur_official(snapshot, runner));
    ASSERT_EQ(snapshot.plan.installs.size(), 3U);
    EXPECT_EQ(snapshot.plan.installs.back().name, "runtime");
    EXPECT_EQ(snapshot.plan.installs.back().repo, "core");
    EXPECT_EQ(snapshot.aur_official.size(), 2U);
    EXPECT_NE(snapshot.fingerprint.find(runner.result.out), std::string::npos);
    const auto baseline = snapshot.fingerprint;
    runner.result.out = "extra/compiler 1-1\ncore/runtime 3-1\n";
    Snapshot changed;
    changed.official_deps = snapshot.official_deps;
    ASSERT_TRUE(plan_aur_official(changed, runner));
    EXPECT_NE(baseline, changed.fingerprint);
    const auto& spec = runner.specs.front();
    EXPECT_EQ(spec.executable, "/usr/bin/pacman");
    EXPECT_EQ(spec.args, (std::vector<std::string>{"--sync", "--print", "--print-format", "%r/%n %v", "--needed", "--", "extra/compiler"}));
    EXPECT_EQ(spec.env, (std::vector<std::pair<std::string, std::string>>{{"LC_ALL", "C"}}));
    EXPECT_EQ(spec.timeout, std::chrono::seconds(30));
    EXPECT_EQ(spec.max_stdout, 4U * 1024 * 1024);
}

TEST_F(AurHardening, OfficialPreviewRejectsMalformedDuplicateAndExcessiveOutput) {
    snapshot.official_deps = {"extra/compiler"};
    for (const auto* text : {"extra/compiler\n", "compiler 1-1\n", "extra/compiler 1 2\n", "extra/compiler 1-1\ncore/compiler 1-1\n"}) {
        runner.result.out = text;
        EXPECT_FALSE(plan_aur_official(snapshot, runner)) << text;
    }
    runner.result.out.clear();
    for (int index = 0; index < 513; ++index) runner.result.out += "extra/pkg" + std::to_string(index) + " 1-1\n";
    EXPECT_FALSE(plan_aur_official(snapshot, runner));
    runner.result.out = "extra/compiler 1-1\n";
    runner.result.timed_out = true;
    EXPECT_FALSE(plan_aur_official(snapshot, runner));
}

