TEST_F(AurHardening, FreeSpaceCheckUsesFourGiBAndFailsForUnavailableFilesystem) {
    EXPECT_FALSE(aur_build_space(root / "missing"));
    struct statvfs space{};
    ASSERT_EQ(statvfs(root.c_str(), &space), 0);
    ASSERT_NE(space.f_frsize, 0U);
    const bool enough = space.f_bavail >= (4ULL * 1024 * 1024 * 1024 + space.f_frsize - 1) / space.f_frsize;
    EXPECT_EQ(aur_build_space(root).has_value(), enough);
}

TEST_F(AurHardening, SuccessfulWorkspaceRemovedAndOnlyThreeNewestFailuresRetained) {
    const auto active = root / "active";
    ASSERT_TRUE(core::ensure_private_dir(active));
    for (int index = 0; index < 5; ++index) {
        const auto workspace = root / ("failed" + std::to_string(index));
        ASSERT_TRUE(core::ensure_private_dir(workspace));
        ASSERT_TRUE(core::atomic_write(workspace / "archive", "bytes", 0600));
        ASSERT_TRUE(finish_aur_workspace(root, workspace, false));
        const timespec times[2]{{100 + index, 0}, {100 + index, 0}};
        ASSERT_EQ(utimensat(AT_FDCWD, (workspace / ".failed").c_str(), times, 0), 0);
    }
    EXPECT_TRUE(std::filesystem::exists(active));
    for (int index = 0; index < 5; ++index)
        EXPECT_EQ(std::filesystem::exists(root / ("failed" + std::to_string(index))), index >= 2);
    ASSERT_TRUE(finish_aur_workspace(root, active, true));
    EXPECT_FALSE(std::filesystem::exists(active));
    EXPECT_FALSE(finish_aur_workspace(root, root, true));
    std::filesystem::create_symlink(root / "failed4", root / "link");
    EXPECT_FALSE(finish_aur_workspace(root, root / "link", false));
    EXPECT_TRUE(std::filesystem::exists(root / "failed4/archive"));
}

TEST_F(AurHardening, PidNamespaceKillsDetachedDescendantsWhenBuildParentExits) {
    core::PosixProcessRunner real;
    core::ProcessSpec probe;
    probe.executable = "/usr/bin/bwrap";
    probe.args = {"--unshare-pid", "--dev-bind", "/", "/", "--", "/usr/bin/true"};
    const auto supported = real.run(probe);
    if (!supported || supported->exit_code != 0 || supported->signaled || supported->timed_out)
        GTEST_SKIP() << "bwrap PID namespaces unavailable: " << (supported ? supported->err : supported.error().message);
    if (access("/usr/bin/python3", X_OK) != 0) GTEST_SKIP() << "python3 unavailable";
    auto spec = aur_build_spec(root, root, root);
    spec.args.resize(9);
    spec.args.insert(spec.args.end(), {"/usr/bin/python3", "-I", "-c",
        "import os,sys,time\nr,w=os.pipe()\nif os.fork()==0:\n os.close(r)\n os.setsid()\n os.write(w,b'x')\n os.close(w)\n time.sleep(0.4)\n open(sys.argv[1],'w').write('survived')\n os._exit(0)\nos.close(w)\nos.read(r,1)\nos._exit(0)",
        (root / "survived").string()});
    spec.timeout = std::chrono::seconds(3);
    const auto result = real.run(spec);
    ASSERT_TRUE(result);
    EXPECT_EQ(result->exit_code, 0) << result->err;
    EXPECT_FALSE(result->timed_out);
    std::this_thread::sleep_for(std::chrono::milliseconds(600));
    EXPECT_FALSE(std::filesystem::exists(root / "survived"));
}
