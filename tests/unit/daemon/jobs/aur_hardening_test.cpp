TEST_F(AurHardening, ArchiveReplacementDuringInspectionAndSymlinksFailClosed) {
    runner.during = [&] {
        const auto pinned = runner.specs.back().args[1];
        ASSERT_TRUE(core::atomic_write(archives.front(), "replaced", 0600));
        const auto bytes = core::read_bounded(pinned, 1024, true);
        ASSERT_TRUE(bytes);
        EXPECT_EQ(*bytes, "built archive");
    };
    EXPECT_FALSE(validate());
    runner.during = {};
    const auto target = root / "target";
    ASSERT_TRUE(core::atomic_write(target, "bytes", 0600));
    std::filesystem::remove(archives.front());
    std::filesystem::create_symlink(target, archives.front());
    EXPECT_FALSE(validate());
}

